create policy "trpg campaigns read" on public.trpg_campaigns for select to anon using (true);
create policy "trpg campaigns insert" on public.trpg_campaigns for insert to anon with check (true);
create policy "trpg campaigns update" on public.trpg_campaigns for update to anon using (true) with check (true);
create policy "trpg players read" on public.trpg_players for select to anon using (true);
create policy "trpg players insert" on public.trpg_players for insert to anon with check (true);
create policy "trpg players update" on public.trpg_players for update to anon using (true) with check (true);
create policy "trpg logs read" on public.trpg_logs for select to anon using (true);
create policy "trpg logs insert" on public.trpg_logs for insert to anon with check (char_length(message) <= 2000);
create policy "trpg votes read" on public.trpg_votes for select to anon using (true);
create policy "trpg votes insert" on public.trpg_votes for insert to anon with check (true);
create policy "trpg votes update" on public.trpg_votes for update to anon using (true) with check (true);
create policy "trpg memo read" on public.trpg_memo for select to anon using (true);
create policy "trpg memo insert" on public.trpg_memo for insert to anon with check (char_length(content) <= 4000);
create policy "trpg memo update" on public.trpg_memo for update to anon using (true) with check (char_length(content) <= 4000);

