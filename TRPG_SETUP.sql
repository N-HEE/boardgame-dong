create table if not exists public.trpg_campaigns (
  id text primary key,
  scenario_id text not null,
  title text not null,
  status text not null default 'active' check (status in ('active','ended')),
  current_scene text not null,
  state jsonb not null default '{}'::jsonb,
  version integer not null default 1,
  started_at timestamptz not null default now(),
  ended_at timestamptz
);

create table if not exists public.trpg_players (
  campaign_id text not null references public.trpg_campaigns(id) on delete cascade,
  user_id text not null,
  user_name text not null,
  assigned_number integer not null check (assigned_number between 1 and 5),
  hp integer not null default 10,
  stamina integer not null default 10,
  stamina_date text not null,
  items jsonb not null default '[]'::jsonb,
  primary key (campaign_id,user_id)
);

create table if not exists public.trpg_logs (
  id bigint generated by default as identity primary key,
  campaign_id text not null references public.trpg_campaigns(id) on delete cascade,
  user_id text,
  user_name text,
  kind text not null default 'action',
  message text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.trpg_votes (
  campaign_id text not null references public.trpg_campaigns(id) on delete cascade,
  scene_id text not null,
  vote_id text not null,
  user_id text not null,
  user_name text not null,
  choice_id text not null,
  updated_at timestamptz not null default now(),
  primary key (campaign_id,scene_id,vote_id,user_id)
);

create table if not exists public.trpg_memo (
  campaign_id text primary key references public.trpg_campaigns(id) on delete cascade,
  content text not null default '' check (char_length(content) <= 4000),
  updated_by text,
  updated_name text,
  updated_at timestamptz not null default now(),
  version integer not null default 1
);

alter table public.trpg_campaigns enable row level security;
alter table public.trpg_players enable row level security;
alter table public.trpg_logs enable row level security;
alter table public.trpg_votes enable row level security;
